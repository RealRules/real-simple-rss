<?php
declare(strict_types=1);

require __DIR__ . '/lib.php';
start_session();
send_security_headers();
header('Cache-Control: no-store, no-cache, must-revalidate');

$lockFile = __DIR__ . '/install.lock';
$installed = is_installed();
$locked = $installed || is_file($lockFile);
$csrf = csrf_token();

$error = '';
$done = false;
$form = [
    'db_host'  => 'localhost',
    'db_port'  => '3306',
    'db_name'  => 'real_simple_rss',
    'db_user'  => '',
    'app_name' => 'Real Simple RSS',
    'admin_username' => '',
    'admin_email'    => '',
];

if ($_SERVER['REQUEST_METHOD'] === 'POST' && !$locked) {
    foreach ($form as $key => $default) {
        $form[$key] = trim((string)($_POST[$key] ?? $default));
    }
    $dbPass = (string)($_POST['db_pass'] ?? '');
    $adminPassword = (string)($_POST['admin_password'] ?? '');
    $adminPassword2 = (string)($_POST['admin_password2'] ?? '');

    if (!csrf_check((string)($_POST['csrf'] ?? ''))) {
        $error = 'Your session expired. Please reload the page and try again.';
    } elseif ($form['db_host'] === '' || $form['db_name'] === '' || $form['db_user'] === '') {
        $error = 'Database host, name and user are required.';
    } elseif ($form['app_name'] === '') {
        $error = 'Please provide an application name.';
    } elseif (!preg_match('/^[A-Za-z0-9_.-]{3,50}$/', $form['admin_username'])) {
        $error = 'Username must be 3-50 characters (letters, numbers, dot, dash, underscore).';
    } elseif (!filter_var($form['admin_email'], FILTER_VALIDATE_EMAIL)) {
        $error = 'Please provide a valid email address.';
    } elseif (strlen($adminPassword) < 8) {
        $error = 'Password must be at least 8 characters long.';
    } elseif ($adminPassword !== $adminPassword2) {
        $error = 'The two passwords do not match.';
    } elseif ($form['db_host'] === '' || !preg_match('/^\d+$/', $form['db_port'])) {
        $error = 'Please provide a valid database port.';
    }

    if ($error === '') {
        try {
            $pdo = db_connect($form['db_host'], $form['db_port'], $form['db_name'], $form['db_user'], $dbPass);

            $schemaFile = __DIR__ . '/schema.sql';
            if (!is_file($schemaFile)) {
                throw new RuntimeException('schema.sql is missing from the application directory.');
            }
            $sql = (string)file_get_contents($schemaFile);
            foreach (split_sql($sql) as $statement) {
                $pdo->exec($statement);
            }

            $stmt = $pdo->prepare('SELECT COUNT(*) FROM users WHERE is_admin = 1');
            $stmt->execute();
            $adminCount = (int)$stmt->fetchColumn();
            if ($adminCount === 0) {
                $insert = $pdo->prepare('INSERT INTO users (username, email, password_hash, is_admin) VALUES (?, ?, ?, 1)');
                $insert->execute([
                    $form['admin_username'],
                    $form['admin_email'],
                    password_hash($adminPassword, PASSWORD_DEFAULT),
                ]);
            }

            $config = [
                'installed'   => true,
                'app_name'    => $form['app_name'],
                'db_host'     => $form['db_host'],
                'db_port'     => $form['db_port'],
                'db_name'     => $form['db_name'],
                'db_user'     => $form['db_user'],
                'db_pass'     => $dbPass,
                'cron_secret' => bin2hex(random_bytes(24)),
            ];

            $contents = "<?php\n"
                . "// Real Simple RSS configuration - generated by setup.php on " . date('c') . ".\n"
                . "// Keep this file out of version control and protect it via .htaccess.\n\n"
                . "return " . var_export($config, true) . ";\n";

            if (@file_put_contents(config_path(), $contents, LOCK_EX) === false) {
                throw new RuntimeException(
                    'Could not write config.php. Ensure the application directory is writable, then try again.'
                );
            }
            @chmod(config_path(), 0640);
            @file_put_contents($lockFile, 'installed ' . date('c') . "\n", LOCK_EX);

            $done = true;
        } catch (PDOException $e) {
            error_log('Real Simple RSS setup database error: ' . $e->getMessage());
            $error = 'Could not connect to the database or create the required tables. '
                . 'Please verify the host, port, database name, user and password.';
        } catch (RuntimeException $e) {
            $error = $e->getMessage();
        } catch (Throwable $e) {
            error_log('Real Simple RSS setup error: ' . $e->getMessage());
            $error = 'An unexpected error occurred during setup. Please consult the server error log.';
        }
    }
}

/**
 * Split a SQL script into individual statements.
 */
function split_sql(string $sql): array
{
    $lines = preg_split('/\r\n|\r|\n/', $sql) ?: [];
    $clean = [];
    foreach ($lines as $line) {
        $trimmed = ltrim($line);
        if (strpos($trimmed, '--') === 0) {
            continue;
        }
        $clean[] = $line;
    }
    $statements = [];
    foreach (explode(';', implode("\n", $clean)) as $statement) {
        $statement = trim($statement);
        if ($statement !== '') {
            $statements[] = $statement;
        }
    }
    return $statements;
}
